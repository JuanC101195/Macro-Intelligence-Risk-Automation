"""Write infra/docker/requirements.lock for the Linux recorder image.

Pins the runtime dependency closure of `trading-system` at the versions installed
in the current (tested) virtualenv, with sha256 hashes taken from PyPI for the
wheels the image can use: pure-Python wheels and CPython 3.12 manylinux x86_64.

    .venv\\Scripts\\python.exe infra/docker/lock_requirements.py

Fails if any package has no usable wheel (the image installs with --only-binary).
"""

from __future__ import annotations

import re
import sys
from importlib import metadata
from pathlib import Path

import httpx
from packaging.markers import default_environment
from packaging.requirements import Requirement

ROOT_PACKAGE = "trading-system"
OUT = Path(__file__).with_name("requirements.lock")

# Target platform of the image (python:3.12-slim on amd64).
TARGET_ENV = {
    **default_environment(),
    "sys_platform": "linux",
    "platform_system": "Linux",
    "os_name": "posix",
    "platform_machine": "x86_64",
    "python_version": "3.12",
    "implementation_name": "cpython",
    "extra": "",
}
WHEEL_OK = re.compile(r"-((py2\.)?py3-none-any|cp312-cp312-manylinux[^-]*x86_64"
                      r"|cp3\d+-abi3-manylinux[^-]*x86_64)\.whl$")


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def closure(root: str) -> dict[str, str]:
    """{normalized name: installed version} for runtime deps of root on the target."""
    seen: dict[str, str] = {}
    stack = [root]
    while stack:
        dist = metadata.distribution(stack.pop())
        for spec in dist.requires or []:
            req = Requirement(spec)
            if req.marker and not req.marker.evaluate(TARGET_ENV):
                continue
            name = norm(req.name)
            if name in seen:
                continue
            seen[name] = metadata.version(req.name)
            stack.append(req.name)
    return seen


def wheel_hashes(client: httpx.Client, name: str, version: str) -> list[str]:
    data = client.get(f"https://pypi.org/pypi/{name}/{version}/json").raise_for_status().json()
    return sorted(
        f["digests"]["sha256"] for f in data["urls"]
        if f["packagetype"] == "bdist_wheel" and WHEEL_OK.search(f["filename"])
    )


def main() -> int:
    deps = closure(ROOT_PACKAGE)
    lines = [
        "# Generated by infra/docker/lock_requirements.py from the tested virtualenv.",
        "# Target: CPython 3.12, Linux x86_64. Install with:",
        "#   pip install --only-binary :all: --require-hashes --no-deps -r requirements.lock",
    ]
    missing = []
    with httpx.Client(timeout=30) as client:
        for name in sorted(deps):
            hashes = wheel_hashes(client, name, deps[name])
            if not hashes:
                missing.append(f"{name}=={deps[name]}")
                continue
            lines.append(f"{name}=={deps[name]} \\")
            lines.extend(f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "")
                         for i, h in enumerate(hashes))
    if missing:
        print("No Linux x86_64 cp312 wheel for:", ", ".join(missing), file=sys.stderr)
        return 1
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {len(deps)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
